import json,os,sys
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from tlib import *
import units_a,units_b,units_c
ROOT=os.path.dirname(HERE)
c=json.load(open(os.path.join(ROOT,'units','unit-1.json')))
compras={'id':'t:compras','title':c['title'],'desc':'Preterite tense, indirect object pronouns, demonstrative adjectives and pronouns, shopping and gifts.','vocab':c['vocab'],'notes':c['notes'],'verbs':c['verbs'],'sentences':c['sentences']}
units=[compras]+[f().out() for f in (units_a.rutina,units_a.comida,units_a.familia,units_a.casa,units_b.imperfecto,units_b.salud,units_b.viajes,units_b.escuela,units_c.deporte,units_c.ciudad,units_c.presente)]
# safety checks (same limits the server enforces)
for u in units:
    assert u['title'] and len(u['title'])<=80,u['title']
    for x in u['vocab']: assert x['es'] and x['en'] and len(x['es'])<=120 and len(x['en'])<=160 and '/' not in x['es'],x
    for n in u['notes']: assert len(n['b'])<=4000 and len(n['h'])<=120,n['h']
    for v in u['verbs']:
        if 'forms' in v: assert len(v['forms'])==5 and all(v['forms']) and v.get('en'),v
    for s in u['sentences']: assert '____' in s['s'] and len(s['s'])<=240 and s['a'] and len(s['why'])<=300,s
    assert len(u['vocab'])<=500 and len(u['sentences'])<=300
    seen=set()
    for s in u['sentences']:
        assert s['s'] not in seen,('duplicate sentence',s['s']); seen.add(s['s'])
js='/* Ready-made units. Generated by tools/build_templates.py. */\nvar TEMPLATES='+json.dumps(units,ensure_ascii=False,separators=(',',':'))+';\n'
open(os.path.join(ROOT,'public','templates.js'),'w').write(js)
print(len(units),'units,',sum(len(u['vocab']) for u in units),'vocab,',sum(len(u['sentences']) for u in units),'sentences,',sum(len(u['notes']) for u in units),'notes,',len(js)//1024,'KB')
